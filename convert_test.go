// Converts a 64x32 MONO HWCGfx state to ASCII and back, asserting the multi-line graphics
// framing survives the roundtrip. (This used to be a t.Fail() debug printout.)
func TestConvert(t *testing.T) {
	state := &rwp.HWCState{}

	//state.HWCText = &rwp.HWCText{
	//	Formatting: rwp.HWCText_FMT_HIDE, // This is the default HWCText content known from EvaluatePanelKey() and putting it here is the right thing to do as it corresponds to resetting the HWCText object (it solved an issue with the dynamics between text and graphics on the master behavior for traces. Let me know if this messes up something else (KS)). Actually it does: On PTZ Extreme / UniSketch, it ends up blanking the display out after first rendering the image... some timing issue? Only seems to happen on UniSketch Raw Panel.
	//}
	state.HWCIDs = []uint32{6}
	state.HWCGfx = &rwp.HWCGfx{
		W:         64,
		H:         32,
		ImageData: []byte{0x00, 0x00, 0x04, 0x5D, 0x24, 0x80, 0x00, 0x00, 0x00, 0x00, 0x06, 0xD1, 0xA4, 0x80, 0x00, 0x00, 0x00, 0x00, 0x05, 0x5D, 0x64, 0x80, 0x00, 0x00, 0x00, 0x00, 0x04, 0x51, 0x24, 0x80, 0x00, 0x00, 0x00, 0x00, 0x04, 0x5D, 0x23, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x18, 0x38, 0x00, 0x03, 0x49, 0xA1, 0xC0, 0x00, 0x1C, 0x78, 0x00, 0x04, 0x4A, 0x21, 0x00, 0x00, 0x1E, 0x78, 0x00, 0x04, 0x3A, 0x21, 0xC0, 0x00, 0x1E, 0x38, 0x00, 0x04, 0x0A, 0x21, 0x00, 0x00, 0x1C, 0x18, 0x00, 0x03, 0x31, 0xB9, 0xC0, 0x00, 0x18, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x33, 0x22, 0xEE, 0x30, 0x17, 0x39, 0xCE, 0xEE, 0x44, 0xB6, 0x89, 0x48, 0x24, 0xA5, 0x10, 0x84, 0x44, 0xAA, 0xE9, 0x48, 0x44, 0xA5, 0xCC, 0xE4, 0x47, 0xA2, 0x8E, 0x78, 0x87, 0x39, 0x02, 0x84, 0x34, 0xA2, 0xE9, 0x49, 0x04, 0x25, 0xDC, 0xE4},
	}

	res := InboundMessagesToRawPanelASCIIstrings([]*rwp.InboundMessage{{States: []*rwp.HWCState{state}}})

	if len(res) != 2 {
		t.Fatalf("expected 2 ASCII lines (256 bytes / 170 per line), got %d: %v", len(res), res)
	}
	if !strings.HasPrefix(res[0], "HWCg#6=0/1,64x32:") {
		t.Errorf("unexpected first gfx line header: %s", res[0])
	}
	if !strings.HasPrefix(res[1], "HWCg#6=1:") {
		t.Errorf("unexpected second gfx line header: %s", res[1])
	}

	// And back: the two lines must reassemble into the identical image.
	back := RawPanelASCIIstringsToInboundMessages(res)
	var gfx *rwp.HWCGfx
	for _, msg := range back {
		for _, s := range msg.States {
			if s.HWCGfx != nil {
				gfx = s.HWCGfx
			}
		}
	}
	if gfx == nil {
		t.Fatal("gfx did not survive the ASCII roundtrip")
	}
	if gfx.W != 64 || gfx.H != 32 {
		t.Errorf("gfx dimensions mangled: %dx%d", gfx.W, gfx.H)
	}
	if len(gfx.ImageData) != len(state.HWCGfx.ImageData) {
		t.Fatalf("gfx payload length mangled: %d != %d", len(gfx.ImageData), len(state.HWCGfx.ImageData))
	}
	for i := range gfx.ImageData {
		if gfx.ImageData[i] != state.HWCGfx.ImageData[i] {
			t.Fatalf("gfx payload differs at byte %d", i)
		}
	}
}
